// @ts-nocheck -- a Bun script; the app's tsconfig has no Bun or Node types.
/**
 * Rebuilds src/components/DynamicBG/Seasonal/ChristmasTrackIds.ts: the Spotify track
 * IDs the Christmas snow treats as Christmas songs.
 *
 *   bun scripts/christmas/build-track-ids.ts
 *
 * Source: https://github.com/mackorone/spotify-playlist-archive-2, which snapshots
 * Spotify's editorial playlists daily. Every playlist there whose name is about
 * Christmas or the holidays is read in its "cumulative" form (every track it has ever
 * held), and a track is kept once it has been in at least MIN_PLAYLISTS of them: one
 * alone lets in the ambient filler that "Christmas Focus"-style playlists carry.
 * overrides.json then adds and removes IDs by hand, each as
 * `{ "id": "<track id>", "note": "<song> - <artist>" }`.
 *
 * Run it shortly before a seasonal release, so this year's new holiday songs are in.
 */

import { join } from "node:path";

const ARCHIVE = "https://raw.githubusercontent.com/mackorone/spotify-playlist-archive-2/main";
const MIN_PLAYLISTS = 2;
const CONCURRENCY = 8;
const OUTPUT = join(import.meta.dir, "../../src/components/DynamicBG/Seasonal/ChristmasTrackIds.ts");
const OVERRIDES = join(import.meta.dir, "overrides.json");

// Playlist names that count, and the ones that only look like they do
// ("This Is Billie Holiday", "Summer Holiday 2023", "Written By Natali Noor").
const HOLIDAY_NAME = /\b(christmas\w*|xmas|navidad|noël|natal|holidays?)\b/i;
const NOT_HOLIDAY = /^this is |summer|^written by /i;

type Overrides = { add: { id: string; note: string }[]; remove: { id: string; note: string }[] };

async function text(url: string): Promise<string> {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return res.text();
}

const index = await text(`${ARCHIVE}/playlists/index.md`);
const playlists = [...index.matchAll(/^- \[(.+)\]\(\/playlists\/pretty\/([A-Za-z0-9]{22})\.md\)$/gm)]
  .map(([, name, id]) => ({ id, name: name.replace(/\\(.)/g, "$1") }))
  .filter(({ name }) => HOLIDAY_NAME.test(name) && !NOT_HOLIDAY.test(name));
console.log(`${playlists.length} holiday playlists`);

// Track ID -> how many of those playlists it has been in.
const counts = new Map<string, number>();
const queue = [...playlists];
await Promise.all(
  Array.from({ length: CONCURRENCY }, async () => {
    for (let playlist = queue.shift(); playlist; playlist = queue.shift()) {
      const page = await text(`${ARCHIVE}/playlists/cumulative/${playlist.id}.md`);
      // A table row's first link is the track.
      const ids = new Set(
        [...page.matchAll(/^\| \[(?:\\.|[^\]])*\]\(https:\/\/open\.spotify\.com\/track\/([A-Za-z0-9]{22})\)/gm)].map(
          (m) => m[1]
        )
      );
      for (const id of ids) counts.set(id, (counts.get(id) ?? 0) + 1);
    }
  })
);

const overrides: Overrides = await Bun.file(OVERRIDES).json();
const ids = new Set([...counts].filter(([, n]) => n >= MIN_PLAYLISTS).map(([id]) => id));
for (const { id } of overrides.add) ids.add(id);
for (const { id } of overrides.remove) ids.delete(id);

const sorted = [...ids].sort();
const lines = [];
for (let i = 0; i < sorted.length; i += 5) lines.push(sorted.slice(i, i + 5).join(" "));

await Bun.write(
  OUTPUT,
  `/**
 * Spotify track IDs the Christmas snow treats as Christmas songs (${sorted.length}).
 *
 * Generated by scripts/christmas/build-track-ids.ts on ${new Date().toISOString().slice(0, 10)}: tracks
 * that have been in at least ${MIN_PLAYLISTS} of Spotify's editorial holiday playlists, plus
 * the hand-picked ones in scripts/christmas/overrides.json. Don't edit by hand.
 */
const ChristmasTrackIds = \`
${lines.join("\n")}
\`;

export default ChristmasTrackIds;
`
);
console.log(`${sorted.length} track IDs (${counts.size} seen) -> ${OUTPUT}`);
